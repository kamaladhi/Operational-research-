"""
Regenerate the IP-vs-GP comparison files in results/ from the saved, verified reference solutions.

Writes, for every instance that has both references:
    results/ip_vs_gp_comparison_<Instance>.json
and one table over all instances:
    results/summary.csv   /   results/summary.md

No solver is run; every number comes from the verified rosters (re-validated and recomputed on load).

Usage (from the project root):
    python scripts/generate_comparison_reports.py
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

import pandas as pd  # noqa: E402

from src.comparison import compare_optimization_results, save_comparison  # noqa: E402
from src.parser import parse_xml  # noqa: E402
from src.reference_solutions import has_reference, load_reference  # noqa: E402


def main():
    raw = os.path.join(ROOT, "data", "raw")
    out = os.path.join(ROOT, "results")
    rows = []
    for name in sorted(f[:-4] for f in os.listdir(raw) if f.startswith("Instance") and f.endswith(".xml")):
        ds = parse_xml(os.path.join(raw, name + ".xml"))
        if not (has_reference(ds, "ip") and has_reference(ds, "gp")):
            print(f"{name}: skipped (needs both IP and GP reference solutions)")
            continue
        ip, gp = load_reference(ds, "ip"), load_reference(ds, "gp")
        comp = compare_optimization_results(ip, gp, ds)
        save_comparison(comp, out, filename=f"ip_vs_gp_comparison_{name}.json")
        rows.append({
            "Instance": name,
            "Nurses": len(ds.employees),
            "Days": ds.planning_period.days,
            "Published optimum": comp.benchmark_reference,
            "IP objective": comp.ip_objective,
            "IP proven optimal": comp.ip_proven_optimal,
            "IP gap %": comp.ip_benchmark_gap_pct,
            "IP solve s": round(comp.ip_solve_time, 1),
            "GP objective": comp.gp_objective,
            "GP proven optimal": comp.gp_proven_optimal,
            "GP solve s": round(comp.gp_solve_time, 1),
            "IP unfilled nurse-shifts": comp.ip_coverage.total_understaffing_magnitude,
            "GP unfilled nurse-shifts": comp.gp_coverage.total_understaffing_magnitude,
            "IP request violations": comp.ip_requests.total_violations,
            "GP request violations": comp.gp_requests.total_violations,
            "IP workload range (min)": comp.ip_workload.workload_range,
            "GP workload range (min)": comp.gp_workload.workload_range,
            "IP Jain index": comp.ip_workload.fairness_index,
            "GP Jain index": comp.gp_workload.fairness_index,
            "Hard constraints OK (IP/GP)": f"{comp.ip_validation_passed}/{comp.gp_validation_passed}",
        })
        print(f"{name}: IP {comp.ip_objective:g} (gap {comp.ip_benchmark_gap_pct}%), GP {comp.gp_objective:g}")

    df = pd.DataFrame(rows)
    df.to_csv(os.path.join(out, "summary.csv"), index=False)
    with open(os.path.join(out, "summary.md"), "w", encoding="utf-8") as f:
        f.write("# Verified results summary\n\n"
                "Generated by `scripts/generate_comparison_reports.py` from the saved reference solutions "
                "(each re-validated against the hard constraints and re-computed on loading).\n\n")
        f.write(df.to_markdown(index=False) if hasattr(df, "to_markdown") and _has_tabulate() else df.to_string(index=False))
        f.write("\n")


def _has_tabulate():
    try:
        import tabulate  # noqa: F401
        return True
    except ImportError:
        return False


if __name__ == "__main__":
    main()
